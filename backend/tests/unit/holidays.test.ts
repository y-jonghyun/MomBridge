import { holidayList, isBusinessDay } from '../../src/lib/payout';

/**
 * 음력 공휴일(설날·추석·부처님오신날)은 korean-lunar-calendar로 양력으로 바꿔 계산한다.
 * 바꾸는 방법이나 대체공휴일 규칙이 달라지면 여기서 먼저 깨지도록 2026~2030년을 적어 둔다.
 */
describe('공휴일', () => {
  const at = (y: number, m: number, d: number) => new Date(y, m - 1, d);

  it('2026년', () => {
    expect(holidayList(2026)).toEqual([
      '2026-01-01',                               // 신정
      '2026-02-16', '2026-02-17', '2026-02-18',   // 설날 (2/17)
      '2026-03-01', '2026-03-02',                 // 삼일절(일) + 대체
      '2026-05-05',                               // 어린이날(화)
      '2026-05-24', '2026-05-25',                 // 부처님오신날(일) + 대체
      '2026-06-06',                               // 현충일(토) — 대체 없음
      '2026-08-15', '2026-08-17',                 // 광복절(토) + 대체
      '2026-09-24', '2026-09-25', '2026-09-26',   // 추석 (9/25)
      '2026-10-03', '2026-10-05',                 // 개천절(토) + 대체
      '2026-10-09',                               // 한글날(금)
      '2026-12-25',                               // 성탄절(금)
    ]);
  });

  it('2027년 — 설날이 일요일과 겹쳐 대체공휴일이 생긴다', () => {
    expect(holidayList(2027)).toEqual([
      '2027-01-01',
      '2027-02-06', '2027-02-07', '2027-02-08', '2027-02-09', // 설날(2/7 일) + 대체
      '2027-03-01',
      '2027-05-05',
      '2027-05-13',                                           // 부처님오신날(목)
      '2027-06-06',
      '2027-08-15', '2027-08-16',                             // 광복절(일) + 대체
      '2027-09-14', '2027-09-15', '2027-09-16',               // 추석 (9/15)
      '2027-10-03', '2027-10-04',                             // 개천절(일) + 대체
      '2027-10-09', '2027-10-11',                             // 한글날(토) + 대체
      '2027-12-25', '2027-12-27',                             // 성탄절(토) + 대체
    ]);
  });

  it('2028년 — 추석이 개천절과 겹쳐 대체공휴일이 생긴다', () => {
    expect(holidayList(2028)).toEqual([
      '2028-01-01',
      '2028-01-26', '2028-01-27', '2028-01-28',  // 설날 (1/27)
      '2028-03-01',
      '2028-05-02',                              // 부처님오신날(화)
      '2028-05-05',
      '2028-06-06',
      '2028-08-15',
      '2028-10-02', '2028-10-03', '2028-10-04',  // 추석 (10/3) — 개천절과 같은 날
      '2028-10-05',                              // 겹친 만큼 대체
      '2028-10-09',
      '2028-12-25',
    ]);
  });

  it('2029년', () => {
    expect(holidayList(2029)).toEqual([
      '2029-01-01',
      '2029-02-12', '2029-02-13', '2029-02-14',  // 설날 (2/13)
      '2029-03-01',
      '2029-05-05', '2029-05-07',                // 어린이날(토) + 대체
      '2029-05-20', '2029-05-21',                // 부처님오신날(일) + 대체
      '2029-06-06',
      '2029-08-15',
      '2029-09-21', '2029-09-22', '2029-09-23',  // 추석 (9/22) — 연휴에 일요일 포함
      '2029-09-24',                              // 그래서 대체
      '2029-10-03',
      '2029-10-09',
      '2029-12-25',
    ]);
  });

  it('2030년', () => {
    expect(holidayList(2030)).toEqual([
      '2030-01-01',
      '2030-02-02', '2030-02-03', '2030-02-04',  // 설날 (2/3 일)
      '2030-02-05',                              // 그래서 대체
      '2030-03-01',
      '2030-05-05', '2030-05-06',                // 어린이날(일) + 대체
      '2030-05-09',                              // 부처님오신날(목)
      '2030-06-06',
      '2030-08-15',
      '2030-09-11', '2030-09-12', '2030-09-13',  // 추석 (9/12)
      '2030-10-03',
      '2030-10-09',
      '2030-12-25',
    ]);
  });

  it('음력 공휴일도 영업일 판정에 들어간다', () => {
    expect(isBusinessDay(at(2026, 2, 17))).toBe(false); // 설날
    expect(isBusinessDay(at(2026, 9, 25))).toBe(false); // 추석
    expect(isBusinessDay(at(2026, 5, 25))).toBe(false); // 부처님오신날 대체
    expect(isBusinessDay(at(2026, 2, 19))).toBe(true);  // 설날 다음 날(목)
  });
});
